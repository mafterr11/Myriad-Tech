// Regenerates lib/projects/snapshot.js from the live database.
//
// The snapshot is the last line of defence behind the Next.js data cache and
// the per-instance memory cache: if Supabase is unreachable on a cold server,
// the homepage and the projects page still render real work instead of an
// empty state. Run it after publishing, unpublishing or reordering projects:
//
//   node scripts/generate-project-snapshot.mjs
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const target = resolve(root, "lib/projects/snapshot.js");

const COLUMNS = [
  "id",
  "slug",
  "name",
  "category",
  "description_ro",
  "description_en",
  "image_url",
  "project_url",
  "github_url",
  "is_published",
  "is_featured",
  "featured_order",
  "sort_order",
  "created_at",
  "updated_at",
];

async function readEnv() {
  const files = [".env.local", ".env"];
  const env = { ...process.env };

  for (const file of files) {
    let contents;
    try {
      contents = await readFile(resolve(root, file), "utf8");
    } catch {
      continue;
    }

    for (const line of contents.split(/\r?\n/)) {
      const match = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
      if (match && !process.env[match[1]]) {
        env[match[1]] = match[2].replace(/^["']|["']$/g, "");
      }
    }
  }

  return env;
}

const env = await readEnv();
const url = env.NEXT_PUBLIC_SUPABASE_URL;
const key = env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY;

if (!url || !key) {
  console.error(
    "Missing NEXT_PUBLIC_SUPABASE_URL or NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY.",
  );
  process.exit(1);
}

const endpoint = new URL(`${url}/rest/v1/projects`);
endpoint.searchParams.set("select", COLUMNS.join(","));
endpoint.searchParams.set("is_published", "eq.true");
endpoint.searchParams.set("order", "sort_order.asc,created_at.asc,id.asc");

const response = await fetch(endpoint, {
  headers: { apikey: key, Authorization: `Bearer ${key}` },
});

if (!response.ok) {
  console.error(`Supabase replied ${response.status}: ${await response.text()}`);
  process.exit(1);
}

const rows = await response.json();

if (!Array.isArray(rows) || rows.length === 0) {
  console.error("Refusing to write an empty snapshot.");
  process.exit(1);
}

const file = `// Generated by scripts/generate-project-snapshot.mjs — do not edit by hand.
//
// Published projects as they were on ${new Date().toISOString().slice(0, 10)}. This is the last
// fallback used when Supabase cannot be reached, so the public pages never
// render an empty portfolio. Regenerate it after changing published projects.
export const PUBLISHED_PROJECTS_SNAPSHOT = ${JSON.stringify(rows, null, 2)};
`;

await writeFile(target, file, "utf8");
console.log(`Wrote ${rows.length} published projects to lib/projects/snapshot.js`);
